function setLang(lang){
 const dict=translations[lang]||translations.zh;
 document.documentElement.lang=lang==="zh"?"zh-CN":lang;
 document.querySelectorAll("[data-i18n]").forEach(el=>{const k=el.dataset.i18n;if(dict[k])el.textContent=dict[k]});
 document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{const k=el.dataset.i18nPlaceholder;if(dict[k])el.placeholder=dict[k]});
 document.querySelectorAll(".lang-btn").forEach(b=>b.classList.toggle("active",b.dataset.lang===lang));
 localStorage.setItem("gyxLang",lang);
}

function showResult(query){
 const q=(query||"").trim();
 const result=recommendations.find(r=>r.keys.some(k=>q.toLowerCase().includes(k.toLowerCase())))||{
  title:"综合数字化解决方案",
  desc:"建议先从需求诊断开始，再组合网站、AI 与自动化能力。",
  tags:["需求诊断","网站建设","人工智能","自动化运营"]
 };
 document.getElementById("resultPanel").innerHTML=`<div class="result-card"><span class="eyebrow">AI MATCHED SOLUTION</span><h3>${result.title}</h3><p>${result.desc}</p><div class="result-tags">${result.tags.map(t=>`<span>${t}</span>`).join("")}</div></div>`;
 document.getElementById("recommend").scrollIntoView({behavior:"smooth"});
}

function bindSearch(formId,inputId){
 const form=document.getElementById(formId),input=document.getElementById(inputId);
 form.addEventListener("submit",e=>{e.preventDefault();showResult(input.value)});
}

